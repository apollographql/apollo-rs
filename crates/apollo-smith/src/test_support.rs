//! Helpers for the property tests in each generator module.

use crate::ArbitraryDocument;
use crate::DocumentBuilder;
use apollo_compiler::ast;
use arbitrary::Arbitrary;
use arbitrary::Result;
use arbitrary::Unstructured;
use proptest::prelude::*;
use std::fmt;

pub(crate) fn input() -> impl Strategy<Value = Vec<u8>> {
    prop::collection::vec(any::<u8>(), 0..=2048)
}

/// Run `generate` on a builder that starts from `schema`, and return the
/// schema with the generated definition added, or `None` when nothing was
/// generated.
pub(crate) fn generate<D: Into<ast::Definition>>(
    schema: &str,
    data: &[u8],
    generate: impl FnOnce(&mut DocumentBuilder<'_>) -> Result<Option<D>>,
) -> Option<String> {
    let definition = generate_definition(schema, data, generate)?;
    Some(format!("{schema}\n{definition}"))
}

pub(crate) fn generate_definition<D: Into<ast::Definition>>(
    schema: &str,
    data: &[u8],
    generate: impl FnOnce(&mut DocumentBuilder<'_>) -> Result<Option<D>>,
) -> Option<String> {
    let mut u = Unstructured::new(data);
    let doc = apollo_compiler::ast::Document::parse(schema, "schema.graphql")
        .expect("parse compiler document");
    let mut builder = DocumentBuilder::with_document(&mut u, doc).expect("builder from schema");
    let definition = generate(&mut builder).ok()??;
    let mut generated = ast::Document::new();
    generated.definitions.push(definition.into());
    Some(generated.to_string())
}

/// What a generator produced from some input. Its `Debug` shows the
/// generated GraphQL rather than the input bytes, so shrunk failures and
/// the `# shrinks to` comments in saved regressions can be read directly.
#[derive(Clone)]
pub(crate) struct Generated {
    /// The schema with what was generated, to validate.
    pub(crate) document: Option<String>,
    shown: Option<String>,
}

impl Generated {
    pub(crate) fn new(document: Option<String>, shown: Option<String>) -> Self {
        Self { document, shown }
    }
}

impl fmt::Debug for Generated {
    // proptest ignores everything after `#` on a saved regression line, so
    // the GraphQL has to stay on one line.
    fn fmt(&self, f: &mut fmt::Formatter<'_>) -> fmt::Result {
        let Some(shown) = &self.shown else {
            return f.write_str("nothing generated");
        };
        let compact = match ast::Document::parse(shown, "smith.graphql") {
            Ok(doc) => doc.serialize().no_indent().to_string(),
            Err(with_errors) => with_errors.partial.serialize().no_indent().to_string(),
        };
        f.write_str(&compact.replace('\r', "\\r").replace('\n', "\\n"))
    }
}

/// Definitions or operations generated by `generate` against `schema`, shown
/// without the schema since it's the same for every case.
pub(crate) fn generated<D: Into<ast::Definition> + 'static>(
    schema: &'static str,
    generate: fn(&mut DocumentBuilder<'_>) -> Result<Option<D>>,
) -> impl Strategy<Value = Generated> {
    generated_from(input(), schema, generate)
}

/// Like `generated`, from input drawn from `bytes`.
pub(crate) fn generated_from<D: Into<ast::Definition> + 'static>(
    bytes: impl Strategy<Value = Vec<u8>>,
    schema: &'static str,
    generate: fn(&mut DocumentBuilder<'_>) -> Result<Option<D>>,
) -> impl Strategy<Value = Generated> {
    bytes.prop_map(move |data| {
        let definition = generate_definition(schema, &data, generate);
        let document = definition.as_ref().map(|d| format!("{schema}\n{d}"));
        Generated::new(document, definition)
    })
}

/// Like `generated`, against one of `schemas`. Each case shows its schema
/// too, since it differs between cases.
pub(crate) fn generated_against_any<D: Into<ast::Definition> + 'static>(
    schemas: &'static [&'static str],
    generate: fn(&mut DocumentBuilder<'_>) -> Result<Option<D>>,
) -> impl Strategy<Value = Generated> {
    prop::sample::select(schemas).prop_flat_map(move |schema| {
        generated(schema, generate).prop_map(|case| {
            let shown = case.document.clone();
            Generated::new(case.document, shown)
        })
    })
}

/// Whole documents from `build()`, through their `Arbitrary` implementation.
pub(crate) fn documents(bytes: impl Strategy<Value = Vec<u8>>) -> impl Strategy<Value = Generated> {
    bytes.prop_map(|data| {
        let document = ArbitraryDocument::arbitrary_take_rest(Unstructured::new(&data))
            .ok()
            .map(|doc| doc.0.to_string());
        Generated::new(document.clone(), document)
    })
}

/// Fail the current case when `doc` has validation errors.
pub(crate) fn prop_assert_valid(doc: &str) -> std::result::Result<(), TestCaseError> {
    let errors: Vec<String> = match ast::Document::parse(doc, "smith.graphql")
        .expect("smith output must parse")
        .to_mixed_validate()
    {
        Ok(_) => vec![],
        Err(errors) => errors
            .iter()
            .map(|e| e.error.to_string())
            // A test generates one definition, so fragments in its schema
            // are only used when that definition happens to spread them.
            .filter(|m| !m.contains("must be used in an operation"))
            .collect(),
    };
    prop_assert!(errors.is_empty(), "{doc}\n{errors:#?}");
    Ok(())
}
